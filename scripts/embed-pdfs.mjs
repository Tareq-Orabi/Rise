import { readFile, writeFile } from 'node:fs/promises';
import { plans } from '../src/plan-content.js';

const pdfAssets = {};
for (const plan of plans) {
  const source = new URL(`../pdf/${plan.id}.pdf`, import.meta.url);
  const bytes = await readFile(source);
  if (bytes.subarray(0, 5).toString('ascii') !== '%PDF-') {
    throw new Error(`Expected a PDF for ${plan.id}`);
  }
  pdfAssets[plan.id] = `data:application/pdf;base64,${bytes.toString('base64')}`;
}

await writeFile(new URL('../src/pdf-assets.js', import.meta.url),
  `// Generated by scripts/embed-pdfs.mjs\nexport const pdfAssets = ${JSON.stringify(pdfAssets)};\n`);
console.log(`Embedded ${plans.length} PDF files.`);
